/**
 * Собирает сводные файлы документации для загрузки в контекст модели:
 * `llms-full.txt` (русский) и `llms-full.en.txt` (английский). Список и порядок
 * файлов заданы здесь, поэтому «актуальность» проверяема: `--check` падает, если
 * файл на диске отличается от пересобранного.
 *
 * Запуск: `npm run docs:llm` (пересобрать) или `npm run docs:check` (проверить).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const VERSIONS = 'Версии / versions: bso5 0.4.0, bso5-components 0.2.0.';
const BAR = '='.repeat(78);

/**
 * Порядок важен: сначала справочник (факты), потом рецепты и разметка,
 * затем вводные README — так модель получает самое плотное знание первым.
 */
const SETS = [
  {
    out: 'llms-full.txt',
    title: '# bso5 — полная документация одним файлом',
    intro: '> Сгенерировано `scripts/build-llm-docs.mjs`. Не редактируйте вручную: правьте\n> источники и запустите `npm run docs:llm`.',
    files: [
      'docs/API.md',
      'docs/GUIDE.md',
      'docs/TREE_GRID.md',
      'packages/bso5/README.md',
      'packages/bso5-components/README.md',
      'docs/README.md',
    ],
  },
  {
    out: 'llms-full.en.txt',
    title: '# bso5 — full documentation in one file',
    intro: '> Generated by `scripts/build-llm-docs.mjs`. Do not edit by hand: change the\n> sources and run `npm run docs:llm`.\n> Markup/class reference (docs/TREE_GRID.md) is Russian-only; the class list is also\n> in docs/API.en.md §12.',
    files: [
      'docs/API.en.md',
      'docs/GUIDE.en.md',
      'packages/bso5/README.en.md',
      'packages/bso5-components/README.en.md',
    ],
  },
];

/**
 * Читает источник с нормализацией переводов строк: на Windows git выкладывает
 * файлы с CRLF, и без этого сводный файл «устаревал» в свежем клоне.
 */
const read = rel => readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n');

function build(set) {
  const parts = set.files.map(rel =>
    `${BAR}\nFILE: ${rel}\n${BAR}\n\n${read(rel).trimEnd()}\n`);

  const header = [
    set.title,
    '',
    set.intro,
    '',
    VERSIONS,
    '',
    `Источники / sources (${set.files.length}): ${set.files.join(', ')}.`,
    '',
  ].join('\n');

  return `${header}\n${parts.join('\n')}`;
}

const check = process.argv.includes('--check');
let failed = false;

for (const set of SETS) {
  const content = build(set);
  const target = join(root, set.out);

  if (!check) {
    writeFileSync(target, content, 'utf8');
    console.log(`${set.out} собран: ${content.length} символов, ${set.files.length} файлов`);
    continue;
  }

  let existing = '';
  try {
    // Сравниваем без учёта стиля переводов строк: у кого-то рабочая копия CRLF
    // (autocrlf), и это не повод объявлять файл устаревшим.
    existing = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    console.error(`${set.out} отсутствует — запустите npm run docs:llm`);
    failed = true;
    continue;
  }
  if (existing !== content) {
    console.error(`${set.out} устарел — запустите npm run docs:llm`);
    failed = true;
    continue;
  }
  console.log(`${set.out} актуален (${content.length} символов)`);
}

if (failed) process.exit(1);
